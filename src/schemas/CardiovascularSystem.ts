import { z } from 'zod';

export const cardiovascularSystemSchema = z.object({
  chiefComplaints: z.string().optional(),
  dyspnea: z.object({
    duration: z.string().optional(),
    onset: z.string().optional(),
    grade: z.string().optional(),
    progression: z.string().optional(),
    aggravatingFactors: z.string().optional(),
    relievingFactors: z.string().optional(),
    orthopnea: z.string().optional(),
    trepopnea: z.string().optional(),
    platypnea: z.string().optional(),
    bendopnea: z.string().optional(),
    paroxysmalNocturnalDyspnea: z.string().optional(),
    associatedSymptoms: z.string().optional(),
  }).optional(),
  chestPain: z.object({
    duration: z.string().optional(),
    onset: z.string().optional(),
    site: z.string().optional(),
    type: z.string().optional(),
    radiation: z.string().optional(),
    nocturnalAngina: z.string().optional(),
    aggravatingFactors: z.string().optional(),
    relievingFactors: z.string().optional(),
    associatedSymptoms: z.string().optional(),
  }).optional(),
  palpitations: z.object({
    duration: z.string().optional(),
    onset: z.string().optional(),
    fastOrSlow: z.string().optional(),
    regularOrIrregular: z.string().optional(),
    precipitatingFactors: z.string().optional(),
    associatedSymptoms: z.string().optional(),
  }).optional(),
  syncope: z.object({
    duration: z.string().optional(),
    onset: z.string().optional(),
    numberOfAttacks: z.string().optional(),
    awareness: z.string().optional(),
    precipitatingFactors: z.string().optional(),
    associatedSymptoms: z.string().optional(),
  }).optional(),
  pedalEdema: z.object({
    duration: z.string().optional(),
    onset: z.string().optional(),
    progression: z.string().optional(),
    aggravatingFactors: z.string().optional(),
    relievingFactors: z.string().optional(),
    facialPuffiness: z.string().optional(),
  }).optional(),
  pastHistory: z.object({
    asthma: z.string().optional(),
    copd: z.string().optional(),
    tuberculosis: z.string().optional(),
    tbContact: z.string().optional(),
    dm: z.string().optional(),
    htn: z.string().optional(),
    ihd: z.string().optional(),
    seizureDisorder: z.string().optional(),
    other: z.string().optional(),
  }).optional(),
  familyHistory: z.string().optional(),
  personalHistory: z.object({
    bowelHabits: z.string().optional(),
    bladderHabits: z.string().optional(),
    appetite: z.string().optional(),
    weightLoss: z.string().optional(),
    occupationalExposure: z.string().optional(),
    sleep: z.string().optional(),
    dietaryHabitsTaboo: z.string().optional(),
    foodAllergies: z.string().optional(),
    smokingIndexPackYears: z.string().optional(),
    alcoholHistory: z.string().optional(),
    other: z.string().optional(),
  }).optional(),
  menstrualObstetricHistory: z.object({
    gpala: z.string().optional(),
    ageMenarche: z.string().optional(),
    menopauseAge: z.string().optional(),
    flowDetails: z.string().optional(),
    other: z.string().optional(),
  }).optional(),
});

export type CardiovascularSystem = z.infer<typeof cardiovascularSystemSchema>;